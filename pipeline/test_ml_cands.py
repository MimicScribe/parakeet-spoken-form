def run() -> int:
    bad = 0
    tot = {}
    for lang, cases in CASES.items():
        ok = 0
        for text, want in cases:
            sp = M.spans(text, lang)
            first = sp[0] if sp else None
            if want is None:
                good = first is None or not first.cands
            elif want == []:
                good = not sp or not sp[0].cands
            else:
                cs = first.cands if first else []
                good = bool(cs) and all(
                    (w[1:] == cs[0]) if w.startswith("=") else any(w == c or w in c.split() or w == c for c in cs)
                    for w in want)
            ok += good
            if not good:
                bad += 1
                print(f"FAIL {lang}: {text!r} want {want} got {first.cands if first else None} "
                      f"({first.kind if first else '-'} {first.note if first else ''})")
        tot[lang] = f"{ok}/{len(cases)}"
    print("PASS", tot)
    return bad


if __name__ == "__main__":
    sys.exit(1 if run() else 0)
